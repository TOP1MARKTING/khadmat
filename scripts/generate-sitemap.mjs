/**
 * Build-time sitemap for Phase 1 knowledge pages only.
 * Excludes: commercial paths, /sa/* matrices, admin, drafts.
 * Omits lastmod — no fabricated dates.
 * Also writes seo-catalog.json for share-preview / prerender.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  SITE,
  buildSeoCatalog,
  extractArticles,
  extractCities,
  extractServices,
} from './lib/seo-catalog.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')

const servicesSrc = readFileSync(resolve(root, 'src/data/services.ts'), 'utf8')
const citiesSrc = readFileSync(resolve(root, 'src/data/cities.ts'), 'utf8')
const blogSrc = readFileSync(resolve(root, 'src/data/blog.ts'), 'utf8')

/** Hold newly completed guides for a separate sitemap publish review. */
const SITEMAP_CONTENT_HOLD = new Set([
  'office-cleaning',
  'upholstery-cleaning',
  'furniture-assembly',
  'office-relocation',
  'facility-management',
])

/** Full eligible guides (for meta catalog / prerender). */
const servicesEligible = extractServices(servicesSrc, { minBody: 120 })
/** Sitemap: eligible guides minus held slugs awaiting separate publish review. */
const servicesForSitemap = servicesEligible.filter(
  (s) => !SITEMAP_CONTENT_HOLD.has(s.slug),
)
/** Routing allowlist: every real service detail page must not hard-404. */
const servicesForRoutes = extractServices(servicesSrc, { minBody: 0 })
const cities = extractCities(citiesSrc)
const articles = extractArticles(blogSrc)

const serviceSlugsForSitemap = servicesForSitemap.map((s) => s.slug)
const serviceSlugsForRoutes = servicesForRoutes.map((s) => s.slug)
const citySlugs = cities.map((c) => c.slug)
const articleSlugs = articles.map((a) => a.slug)

const staticPaths = [
  '/',
  '/services',
  '/locations',
  '/about',
  '/contact',
  '/blog',
  '/privacy',
  '/terms',
]

const urls = [
  ...staticPaths,
  ...serviceSlugsForSitemap.map((s) => `/services/${s}`),
  ...citySlugs.map((c) => `/locations/${c}`),
  ...articleSlugs.map((a) => `/blog/${a}`),
]

const routeUrls = [
  ...staticPaths,
  ...serviceSlugsForRoutes.map((s) => `/services/${s}`),
  ...citySlugs.map((c) => `/locations/${c}`),
  ...articleSlugs.map((a) => `/blog/${a}`),
]

function escapeXml(s) {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

const body = urls
  .map(
    (path) => `  <url>
    <loc>${escapeXml(SITE + (path === '/' ? '/' : path))}</loc>
  </url>`,
  )
  .join('\n')

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${body}
</urlset>
`

writeFileSync(resolve(root, 'public/sitemap.xml'), xml, 'utf8')

const catalog = buildSeoCatalog({
  services: servicesEligible,
  cities,
  articles,
})
const catalogJson = `${JSON.stringify(catalog, null, 2)}\n`
writeFileSync(resolve(root, 'public/seo-catalog.json'), catalogJson, 'utf8')
writeFileSync(resolve(root, 'api/seo-catalog.json'), catalogJson, 'utf8')

/** Exact paths allowed through SPA (unknown paths → real HTTP 404). */
const allowExact = new Set([...routeUrls, '/home', '/admin', '/admin/login'])
/** /blog/ prefix: CMS articles load from Firebase without a rebuild. */
const allowPrefixes = ['/admin/', '/assets/', '/blog/', '/images/', '/sa/']
const allowlistJs = `/** Auto-generated by scripts/generate-sitemap.mjs — do not edit */
export const ALLOW_EXACT = new Set(${JSON.stringify([...allowExact].sort())});
export const ALLOW_PREFIXES = ${JSON.stringify(allowPrefixes)};
`
writeFileSync(resolve(root, 'path-allowlist.js'), allowlistJs, 'utf8')

/**
 * SPA rewrites for known routes only — no catch-all.
 * Unknown paths fall through to Vercel filesystem → real HTTP 404.
 * Middleware remains a second layer for the same allowlist.
 */
const spaRewrites = [
  // Do NOT rewrite google*.html — serve the static file from /public as-is.
  { source: '/', destination: '/index.html' },
  ...[...allowExact]
    .filter((p) => p !== '/')
    .sort()
    .map((p) => ({ source: p, destination: '/index.html' })),
  // Trailing slash on blog index → same SPA shell as /blog
  { source: '/blog/', destination: '/index.html' },
  // Dynamic admin + regional matrices (still SPA)
  { source: '/admin/:path*', destination: '/index.html' },
  { source: '/sa/:path*', destination: '/index.html' },
  // CMS articles without rebuild (unknown slugs → app NotFoundPage)
  { source: '/blog/:path*', destination: '/index.html' },
]

const vercelJson = {
  headers: [
    {
      source: '/googlefcf192a19b3a8b5c.html',
      headers: [
        { key: 'Content-Type', value: 'text/plain; charset=utf-8' },
        { key: 'Cache-Control', value: 'no-store, max-age=0, must-revalidate' },
        { key: 'X-Robots-Tag', value: 'noindex' },
      ],
    },
    {
      source: '/admin',
      headers: [{ key: 'X-Robots-Tag', value: 'noindex, nofollow, noarchive' }],
    },
    {
      source: '/admin/:path*',
      headers: [{ key: 'X-Robots-Tag', value: 'noindex, nofollow, noarchive' }],
    },
  ],
  rewrites: spaRewrites,
}

writeFileSync(
  resolve(root, 'vercel.json'),
  `${JSON.stringify(vercelJson, null, 2)}\n`,
  'utf8',
)

console.log(
  `sitemap.xml → ${urls.length} urls (${serviceSlugsForSitemap.length} services, ${citySlugs.length} cities, ${articleSlugs.length} articles); routes ${serviceSlugsForRoutes.length}; vercel rewrites → ${spaRewrites.length}; seo-catalog → ${Object.keys(catalog).length}`,
)
